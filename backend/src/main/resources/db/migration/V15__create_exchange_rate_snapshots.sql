CREATE TABLE exchange_rate_snapshots (
    currency VARCHAR(3) NOT NULL,
    rate_date DATE NOT NULL,
    -- 1단위 외화 = 몇 원인지(KRW 환산가). 값 자체는 무료 공개 API(Frankfurter/ECB 기준)에서
    -- 받아온 실측치이며, 임의로 지어낸 수치가 아님
    rate DECIMAL(12, 4) NOT NULL,
    PRIMARY KEY (currency, rate_date)
);

CREATE INDEX idx_exchange_rate_snapshots_currency_date ON exchange_rate_snapshots(currency, rate_date DESC);

